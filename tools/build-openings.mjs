#!/usr/bin/env node
/**
 * Generates src/data/openings.js from the MIT-licensed eco-chess dataset.
 *
 * Every line is replayed through chess.js before it is emitted — the source is
 * hand-maintained and a bad SAN string would otherwise show up as a wrong
 * opening name at runtime, which is worse than no name at all.
 *
 *   npm pack eco-chess@1.0.3 && tar xzf eco-chess-1.0.3.tgz
 *   node tools/build-openings.mjs path/to/package/tree-with-moves.json
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from 'chess.js';
import { format, resolveConfig } from 'prettier';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) {
  console.error('usage: node tools/build-openings.mjs <tree-with-moves.json>');
  process.exit(2);
}

const tree = JSON.parse(await readFile(source, 'utf8'));

/**
 * Two lines in the upstream data are unplayable as written. Both are plain
 * transcription slips rather than disagreements about theory, so they are
 * corrected here instead of dropped.
 */
const CORRECTIONS = new Map([
  // Rossolimo is 3.Bb5, not 3.Bg5 (which is illegal here anyway).
  ['1. e4 c5 2. Nf3 Nc6 3. Bg5 g6', '1. e4 c5 2. Nf3 Nc6 3. Bb5 g6'],
]);

/** Strips move numbers, leaving bare SAN tokens. */
function toSanList(moves) {
  return (CORRECTIONS.get(moves.trim()) ?? moves)
    .replace(/\d+\.(\.\.)?/g, ' ')
    .split(/[\s,]+/)
    .map((token) => token.trim())
    .filter(Boolean);
}

/**
 * The dataset occasionally uses the abbreviated capture form (`dc` for `dxc6`).
 * Resolve it against the position rather than guessing the destination rank.
 */
function expandAbbreviatedCapture(chess, token) {
  const match = /^([a-h])([a-h])$/.exec(token);
  if (!match) return token;
  const [, fromFile, toFile] = match;
  const candidate = chess
    .moves({ verbose: true })
    .find((move) => move.piece === 'p' && move.from[0] === fromFile && move.to[0] === toFile);
  return candidate ? candidate.san : token;
}

const entries = [];
let rejected = 0;

function visit(key, node) {
  if (!node || typeof node !== 'object') return;
  const eco = key.includes('-') ? key.split('-')[0] : key;

  if (typeof node.moves === 'string' && typeof node.name === 'string') {
    // A few entries list alternative first moves separated by commas; each is
    // its own line, so split on the comma and validate them independently.
    const alternatives = node.moves.includes(',')
      ? node.moves.split(',').map((part) => part.trim())
      : [node.moves];
    for (const alternative of alternatives) {
      const san = toSanList(alternative);
      if (!san.length) continue;
      const chess = new Chess();
      let ok = true;
      for (const [index, move] of san.entries()) {
        const resolved = expandAbbreviatedCapture(chess, move);
        san[index] = resolved;
        try {
          if (!chess.move(resolved)) ok = false;
        } catch {
          ok = false;
        }
        if (!ok) break;
      }
      if (!ok) {
        rejected++;
        console.warn(`  rejected ${eco} "${node.name}": ${alternative}`);
        continue;
      }
      entries.push({ eco, name: node.name, san });
    }
  }

  for (const [childKey, child] of Object.entries(node)) {
    if (childKey === 'name' || childKey === 'moves') continue;
    visit(childKey, child);
  }
}

for (const [key, node] of Object.entries(tree)) visit(key, node);

// Longest line first so a prefix lookup naturally resolves to the most specific
// name; de-duplicate identical sequences, keeping the first (most specific) one.
entries.sort((a, b) => b.san.length - a.san.length || a.eco.localeCompare(b.eco));
const seen = new Set();
const unique = entries.filter((entry) => {
  const key = entry.san.join(' ');
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const maxPly = Math.max(...unique.map((entry) => entry.san.length));
const table = unique.map((entry) => [entry.san.join(' '), entry.eco, entry.name]);

const module = `/**
 * ECO opening book — generated by tools/build-openings.mjs, do not edit by hand.
 *
 * Source: eco-chess (MIT) by Harijs Deksnis — https://github.com/arcanous/eco-chess
 * Every line below was replayed through chess.js at build time, so each entry is
 * a legal sequence from the standard start position.
 *
 * ${unique.length} lines, longest ${maxPly} plies.
 */

/** \`[sanSequence, eco, name]\`, longest sequence first. */
export const OPENING_TABLE = ${JSON.stringify(table)};

export const MAX_BOOK_PLY = ${maxPly};
`;

// Through the repo's own prettier config: `JSON.stringify` puts the whole table
// on one 35k-character line, which fails `npm run check` and makes every future
// diff of the book unreviewable.
const target = path.join(ROOT, 'src/data/openings.js');
await mkdir(path.dirname(target), { recursive: true });
const output = await format(module, { ...(await resolveConfig(target)), filepath: target });
await writeFile(target, output);

console.log(
  `openings: ${unique.length} lines (${rejected} rejected), longest ${maxPly} plies, ` +
    `${(output.length / 1024).toFixed(1)}KB`,
);
